#!/bin/bash
# ============================================================
# اسکریپت آپدیت امن سامانه دفتر
# استفاده: bash update.sh
# ============================================================
set -e

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "${BLUE}═══════════════════════════════════════${NC}"
echo -e "${BLUE}   آپدیت سامانه دفتر - شروع فرآیند   ${NC}"
echo -e "${BLUE}═══════════════════════════════════════${NC}"

# بررسی اینکه docker compose در حال اجراست
if ! docker compose ps | grep -q "running\|Up"; then
  echo -e "${RED}❌ خطا: سامانه در حال اجرا نیست. ابتدا docker compose up -d را اجرا کنید.${NC}"
  exit 1
fi

# ─────────────────────────────────────────────────
# قدم ۱: بکاپ خودکار قبل از آپدیت
# ─────────────────────────────────────────────────
echo -e "\n${YELLOW}📦 قدم ۱: تهیه بکاپ خودکار از دیتابیس...${NC}"
BACKUP_FILE="./pre_update_backup_$(date +%Y%m%d_%H%M%S).sql.gz"
docker compose exec -T postgres pg_dump \
  -U "${POSTGRES_USER:-daftar_user}" \
  "${POSTGRES_DB:-daftar_db}" | gzip > "$BACKUP_FILE"
echo -e "${GREEN}✅ بکاپ ذخیره شد: $BACKUP_FILE${NC}"

# ─────────────────────────────────────────────────
# قدم ۲: دریافت آخرین کد
# ─────────────────────────────────────────────────
echo -e "\n${YELLOW}🔄 قدم ۲: دریافت آخرین تغییرات از git...${NC}"
git pull
echo -e "${GREEN}✅ کد آپدیت شد.${NC}"

# ─────────────────────────────────────────────────
# قدم ۳: rebuild و restart
# ─────────────────────────────────────────────────
echo -e "\n${YELLOW}🔨 قدم ۳: rebuild سرویس‌ها...${NC}"
docker compose up -d --build

# ─────────────────────────────────────────────────
# قدم ۴: بررسی سلامت سرویس‌ها
# ─────────────────────────────────────────────────
echo -e "\n${YELLOW}⏳ قدم ۴: بررسی سلامت سرویس‌ها (۱۵ ثانیه)...${NC}"
sleep 15
docker compose ps

# ─────────────────────────────────────────────────
# نتیجه
# ─────────────────────────────────────────────────
echo -e "\n${BLUE}═══════════════════════════════════════${NC}"
echo -e "${GREEN}🎉 آپدیت با موفقیت انجام شد!${NC}"
echo -e "${BLUE}═══════════════════════════════════════${NC}"
echo ""
echo -e "💾 بکاپ قبل از آپدیت: ${YELLOW}$BACKUP_FILE${NC}"
echo -e "📌 در صورت بروز مشکل:"
echo -e "   ${RED}git checkout <commit-قبلی>${NC}"
echo -e "   ${RED}docker compose up -d --build${NC}"
echo ""
